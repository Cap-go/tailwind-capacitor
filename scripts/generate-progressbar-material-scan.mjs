import { writeFileSync } from 'node:fs';
import { ProgressbarColors } from '../src/shared/colors/ProgressbarColors.js';
import { ProgressbarClasses } from '../src/shared/classes/ProgressbarClasses.js';

const dark = (classNames) => (classNames ? classNames : '');
const colors = ProgressbarColors({}, dark);
const classes = ProgressbarClasses(colors);

const tokens = new Set([
  'bg-md-light-surface',
  'dark:bg-md-dark-surface',
]);

const collect = (value) => {
  for (const part of String(value).split(/\s+/)) {
    if (/^(?:dark:)?bg-/.test(part)) tokens.add(part);
  }
};

collect(classes.base.common);
collect(classes.base.ios);
collect(classes.base.material);
collect(classes.inner.common);
collect(classes.inner.ios);
collect(classes.inner.material);

const lines = [
  '/* Generated by scripts/generate-progressbar-material-scan.mjs; do not edit. */',
  ...[...tokens].sort().map((u) => `@source inline("${u}");`),
  '',
];

const out = new URL(
  '../registry/capacitor/styles/progressbar-material-scan.css',
  import.meta.url,
);
writeFileSync(out, lines.join('\n'));