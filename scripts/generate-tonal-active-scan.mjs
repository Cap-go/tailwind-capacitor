import { writeFileSync } from 'node:fs';

const PALETTE = [
  'slate',
  'gray',
  'zinc',
  'neutral',
  'stone',
  'red',
  'orange',
  'amber',
  'yellow',
  'lime',
  'green',
  'emerald',
  'teal',
  'cyan',
  'sky',
  'blue',
  'indigo',
  'violet',
  'purple',
  'fuchsia',
  'pink',
  'rose',
];
const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const SEMANTIC = ['primary', 'secondary', 'success', 'warning', 'danger', 'info'];

const sources = new Set();
for (const name of SEMANTIC) {
  sources.add(`active:!bg-${name}/25`);
  for (const opacity of ['15', '20', '25', '30', '35', '40', '45', '50']) {
    sources.add(`active:!bg-${name}/${opacity}`);
  }
}
for (const hue of PALETTE) {
  for (const step of STEPS) {
    sources.add(`active:!bg-${hue}-${step}/25`);
    for (const opacity of ['15', '20', '25', '30', '40', '50']) {
      sources.add(`active:!bg-${hue}-${step}/${opacity}`);
    }
  }
}

const lines = [
  '/* Generated by scripts/generate-tonal-active-scan.mjs; do not edit. */',
  ...[...sources].sort().map((u) => `@source inline("${u}");`),
  '',
];

const out = new URL(
  '../registry/capacitor/styles/tonal-active-scan.css',
  import.meta.url,
);
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out.pathname} (${sources.size} tonal active scan hints)`);